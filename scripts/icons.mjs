// Reads icon geometry out of the installed Font Awesome Free package.
//
// The paths are vendored into src/renderer/ui/icons.ts rather than loaded at
// runtime, because the renderer's content policy allows no font and no image
// (QGD-SEC-0008): a webfont or an <img> sprite would mean widening it, and
// inline SVG markup is not a resource at all. Vendoring makes the copy the
// thing that can drift, so this module is shared by the generator and by the
// test that holds the copy to the package.
//
// Font Awesome Free icons are CC BY 4.0, which requires attribution. That is
// what NOTICE and the About panel are for, and a test keeps them honest.
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

export const PACKAGE = '@fortawesome/fontawesome-free';

// The icons the rail uses, by their Font Awesome names.
export const ICONS = [
  { key: 'home', name: 'house', style: 'solid' },
  { key: 'personas', name: 'id-card', style: 'solid' },
  { key: 'settings', name: 'gear', style: 'solid' }
];

export function fontAwesomeVersion() {
  return require(`${PACKAGE}/package.json`).version;
}

export function extract({ name, style }) {
  const file = require.resolve(`${PACKAGE}/svgs/${style}/${name}.svg`);
  const svg = readFileSync(file, 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg);
  if (!viewBox) throw new Error(`${name}: no viewBox`);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(match => match[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected one path, found ${paths.length}`);
  return { viewBox: viewBox[1], path: paths[0] };
}

// The credit the About panel shows, and the version it names. A separate
// module from the icon geometry because the main process needs it and must
// never import from src/renderer: Vite empties dist/renderer on every build,
// so a main-process import of a file in that tree resolves at compile time and
// is gone by the time the application starts.
export function renderAttribution() {
  const version = fontAwesomeVersion();
  return `// SPDX-License-Identifier: GPL-3.0-only
// GENERATED by scripts/gen-icons.mjs from ${PACKAGE} ${version}. Do not edit.
//
// Attribution for third-party material that ships inside the application.
// Font Awesome Free icons are CC BY 4.0, which requires it. NOTICE is the
// written record; the About panel is the one a user can reach, and this is
// what it says. tests/icons.test.mjs holds the two to each other.
export const FONT_AWESOME_VERSION = '${version}';

export const FONT_AWESOME_CREDIT = [
  'Icons from Font Awesome Free ${version} by Fonticons, Inc.',
  'Licensed under CC BY 4.0 \u2014 https://creativecommons.org/licenses/by/4.0/',
  'https://fontawesome.com'
].join('\\n');
`;
}

export function render() {
  const version = fontAwesomeVersion();
  const entries = ICONS.map(icon => {
    const { viewBox, path } = extract(icon);
    return `  ${icon.key}: {\n` +
      `    name: '${icon.name}',\n` +
      `    viewBox: '${viewBox}',\n` +
      `    path: '${path}'\n` +
      `  }`;
  }).join(',\n');

  return `// SPDX-License-Identifier: GPL-3.0-only
// GENERATED by scripts/gen-icons.mjs from ${PACKAGE} ${version}. Do not edit:
// a hand-edited copy fails tests/icons.test.mjs, which re-reads the package.
//
// Font Awesome Free ${version} — icon geometry under CC BY 4.0.
// https://fontawesome.com · attribution in NOTICE and in the About panel.
//
// Vendored rather than loaded: QGD-SEC-0008 allows the renderer no font and no
// image, and inline SVG markup is neither.
export interface Icon {
  readonly name: string;
  readonly viewBox: string;
  readonly path: string;
}

export const FONT_AWESOME_VERSION = '${version}';

export const ICONS: Record<string, Icon> = {
${entries}
};
`;
}
